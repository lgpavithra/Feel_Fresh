    private void roundButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roundButton1ActionPerformed

        DbInfoBean bean = new DbInfoBean();

        jTextArea1.setText("");

        new Thread() {
            @Override
            public void run() {
                try {
                    Thread.sleep(500);
                } catch (InterruptedException ex) {
                    jTextArea1.setText("Thread.sleep() Error");
                }

                if (jTextFieldHost.getText().trim().isBlank()) {
                    JOptionPane.showMessageDialog(parent, "Please enter host");

                } else if (jTextFieldPort.getText().trim().isBlank()) {
                    JOptionPane.showMessageDialog(parent, "Please enter PORT");

                } else if (jTextFieldUsername.getText().trim().isBlank()) {
                    JOptionPane.showMessageDialog(parent, "Please enter Username");

                } else if (String.valueOf(jPasswordFieldPassword.getPassword()).isBlank()) {
                    JOptionPane.showMessageDialog(parent, "Please enter Password");

                } else if (jTextFieldDBName.getText().trim().isBlank()) {
                    JOptionPane.showMessageDialog(parent, "Please enter Database Name");

                } else {
                    bean.setHost(jTextFieldHost.getText().trim());
                    bean.setPort(jTextFieldPort.getText().trim());
                    bean.setUsername(jTextFieldUsername.getText().trim());
                    bean.setPassword(String.valueOf(jPasswordFieldPassword.getPassword()).trim());
                    bean.setDbName(jTextFieldDBName.getText().trim());

                    //saving
                    try {
                        BeanWriter.getInstance().write(new File("dbInfo.ser"), bean);

                        String responseText = MYSQL.createConnection();
                        if (responseText.equals("Success")) {
                            jTextArea1.setText("Connected Successfully");
                        } else {
                            jTextArea1.setText("Error... Please check database infromations! \n" + responseText);
                        }

                    } catch (FileNotFoundException e) {
                        jTextArea1.setText("Error... \n" + e);
                    } catch (IOException e) {
                        jTextArea1.setText("Error... \n" + e);
                    }
                }

            }

        }.start();

    }//GEN-LAST:event_roundButton1ActionPerformed

