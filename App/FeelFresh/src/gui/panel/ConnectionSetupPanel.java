    private void loadData() {

        File f = new File("dbInfo.ser");
        if (f.exists()) {

            try {
                DbInfoBean bean = (DbInfoBean) BeanReader.getInstance().read(f);
                jTextFieldHost.setText(bean.getHost());
                jTextFieldPort.setText(bean.getPort());
                jTextFieldUsername.setText(bean.getUsername());
                jPasswordFieldPassword.setText(bean.getPassword());
                jTextFieldDBName.setText(bean.getDbName());

            } catch (IOException ex) {
                jTextArea1.setText("Error... \n" + ex);
            } catch (ClassNotFoundException ex) {
                jTextArea1.setText("Error... \n" + ex);
            }

        }

    }
    
    
    
    
    
