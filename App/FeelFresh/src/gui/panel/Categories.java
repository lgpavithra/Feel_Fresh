    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
       updateAndRemoveCategory_vp.jButton1.setEnabled(true);
        if (evt.getClickCount() >= 2) {
            jPanel1.removeAll();
            jPanel1.add(updateAndRemoveCategory_vp);
            updateAndRemoveCategory_vp.currentCategory_vp = String.valueOf(jTable1.getValueAt(jTable1.getSelectedRow(), 1));
            updateAndRemoveCategory_vp.uJTextfield1.setText(updateAndRemoveCategory_vp.currentCategory_vp);
            SwingUtilities.updateComponentTreeUI(jPanel1);
            
           

        } else {
            reset_vp();
            

        }
    }//GEN-LAST:event_jTable1MouseClicked

