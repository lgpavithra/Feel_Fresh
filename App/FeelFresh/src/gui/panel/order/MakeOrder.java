    public void setSupplierId(String supplierId) {
        this.supplierId_vp = supplierId;

        try {
            ResultSet resultSet = MYSQL.executeSearch("SELECT * FROM `supplier` "
                    + " INNER JOIN `supplier_mobile` ON `supplier`.`id` = `supplier_mobile`.`supplier_id` "
                    + " WHERE `id` = '" + supplierId + "'");
            if (resultSet.next()) {

                //Setting the user Details to the textfields in MakeOrder panel
                IdLabel.setText(resultSet.getString("id"));
                nameLabel.setText(resultSet.getString("first_name") + " " + resultSet.getString("last_name"));
                emailLabel.setText(resultSet.getString("email"));
                mobileLabel.setText(resultSet.getString("mobile"));

            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }

    }

    private void loadOrderPending_vp() {

        DefaultListModel listModelPending = new DefaultListModel();
        Boolean pendingAvaliable = false;
        try {
            ResultSet rsOrderHis = MYSQL.executeSearch("SELECT * FROM `order` ");
            while (rsOrderHis.next()) {
                Vector<String> vector = new Vector<>();
                vector.add(rsOrderHis.getString("id") + " " + rsOrderHis.getString("status") + " - " + new SimpleDateFormat("yyyy-MM-dd").format(rsOrderHis.getDate("created_at")));

                if (rsOrderHis.getString("status").equals("Pending")) {

                    pendingAvaliable = true;
                    listModelPending.addElement(vector);
                }
            }


            if (pendingAvaliable) {
                jListPendingOrder.setModel(listModelPending);
                jPanel6.removeAll();
                jPanel6.add(jScrollPanePendingOrder);

            } else {
                jPanel6.removeAll();
                jPanel6.add(jPanel5);
            }
            SwingUtilities.updateComponentTreeUI(this);

        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

