    /**
     * @param productDetails the productDetails_vp to set
     */
    public void setProductDetails(String[] productDetails) {

        // [0] id, [1] product name, [2] brand, [3] category, [4] qty , [5] unit
        clearFilter_vp();

        this.productDetails_vp = productDetails;

        if (jTable1.getRowCount() > 0) {
            Boolean foundColumn = false;
            for (int i = 0; i < jTable1.getRowCount(); i++) {

                if (jTable1.getValueAt(i, 0).equals(productDetails[0])) {//if a row is avaliable

                    foundColumn = true;
                    //update quantity  

                    int option = JOptionPane.showConfirmDialog(this, "This item already exists. "
                            + "Do you want to update the quantity (This will add this quantity to existing quantity)", "Information", JOptionPane.INFORMATION_MESSAGE);

                    if (option == 0) {
                        jTable1.setValueAt(String.valueOf(Double.valueOf(productDetails[4]) + Double.valueOf((String) jTable1.getValueAt(i, 4))), i, 4);
                    }

                }
            }

            if (!foundColumn) {//it is no any row to match
                //set to table 
                Vector<String> vector = new Vector();
                vector.add(productDetails[0]);
                vector.add(productDetails[1]);
                vector.add(productDetails[2]);
                vector.add(productDetails[3]);
                vector.add(productDetails[4]);
                vector.add(productDetails[5]);

                DefaultTableModel dtm = tableModelFull_vp;
                dtm.addRow(vector);
            }

        } else {//row count is zero
            //set to table 
            Vector<String> vector = new Vector();
            vector.add(productDetails[0]);
            vector.add(productDetails[1]);
            vector.add(productDetails[2]);
            vector.add(productDetails[3]);
            vector.add(productDetails[4]);
            vector.add(productDetails[5]);

            DefaultTableModel dtm = tableModelFull_vp;
            dtm.addRow(vector);
        }

        SwingUtilities.updateComponentTreeUI(this);

    }

