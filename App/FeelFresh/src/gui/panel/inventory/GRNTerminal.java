    private void orderComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_orderComboBoxActionPerformed
        try {
            // Get the selected order ID
            String selectedOrder = (String) orderComboBox.getSelectedItem();

            // Validate selection
            if (selectedOrder != null && !selectedOrder.trim().isEmpty() && !selectedOrder.equals("None")) {
                // Set the order ID label
                orderIDValue.setText(selectedOrder);

                // Convert selectedOrder to integer
                int orderId = Integer.parseInt(selectedOrder.trim());

                // Query to get the supplier ID for the selected order
                String query = "SELECT supplier_id FROM `order` WHERE id = " + orderId;
                ResultSet rs = MYSQL.executeSearch(query);

                if (rs.next()) {
                    int supplierId = rs.getInt("supplier_id");

                    // Query to get the full name of the supplier
                    String supplierQuery = "SELECT CONCAT(first_name, ' ', last_name) AS full_name FROM `supplier` WHERE id = " + supplierId;
                    ResultSet supplierRs = MYSQL.executeSearch(supplierQuery);

                    if (supplierRs.next()) {
                        String supplierName = supplierRs.getString("full_name");

                        // Set the corresponding supplier in the supplierComboBox
                        supplierComboBox.setSelectedItem(supplierName);
                    } else {
                        JOptionPane.showMessageDialog(this, "Supplier not found for the selected order.", "Error", JOptionPane.ERROR_MESSAGE);
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Order not found in the database.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } else {
                // Handle invalid selection
                JOptionPane.showMessageDialog(this, "Please select a valid order ID.", "Validation Error", JOptionPane.WARNING_MESSAGE);

                // Clear fields to reset state
                orderIDValue.setText("None");
                supplierComboBox.setSelectedIndex(0);

                // Exit early to prevent additional processing
                return;
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Invalid order ID format: " + ex.getMessage(), "Validation Error", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "An error occurred while selecting supplier: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_orderComboBoxActionPerformed

