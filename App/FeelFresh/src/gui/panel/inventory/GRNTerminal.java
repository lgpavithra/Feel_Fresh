    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        try {
            // Validate product selection before proceeding
            if (!validateProductSelection()) {
                return; // Stop if validation fails
            }

            // Get selected product from the combo box
            String product_name = (String) productComboBox.getSelectedItem();
            String qtyStr = qtyTxtField.getText().trim();
            String buyingPriceStr = buyingPriceTxtField.getText().trim();
            String sellingPriceStr = sellingPriceTxtField.getText().trim();

            // Validate product name
            if (product_name == null || product_name.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please select a product from the list.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Validate numeric fields
            if (qtyStr.isEmpty() || buyingPriceStr.isEmpty() || sellingPriceStr.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Quantity, buying price, and selling price fields cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int qty;
            double buying_price;
            double selling_price;

            try {
                qty = Integer.parseInt(qtyStr);
                buying_price = Double.parseDouble(buyingPriceStr);
                selling_price = Double.parseDouble(sellingPriceStr);
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Please enter valid numeric values for quantity, buying price, and selling price.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Check for positive values
            if (qty <= 0 || buying_price <= 0 || selling_price <= 0) {
                JOptionPane.showMessageDialog(this, "Quantity, buying price, and selling price must be positive values.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Validate that selling price is greater than buying price
            if (selling_price <= buying_price) {
                JOptionPane.showMessageDialog(this, "The selling price must be greater than the buying price.", "Validation Error", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // Calculate subtotal
            double subtotal = qty * buying_price;

            // Create a new product object
            GRNProduct product = new GRNProduct(product_name, qty, buying_price, selling_price, subtotal);

            // Get the DefaultTableModel for the JTable
            DefaultTableModel model = (DefaultTableModel) itemTable.getModel();
            boolean itemExists = false;

            // Loop through the table to check if the product already exists
            for (int row = 0; row < model.getRowCount(); row++) {
                String existingProductName = (String) model.getValueAt(row, 0); // Column 0: Product Name
                if (existingProductName.equals(product_name)) {
                    // If the product already exists, update the quantity and subtotal
                    int existingQty = (int) model.getValueAt(row, 1); // Column 1: Quantity
                    double existingSubtotal = (double) model.getValueAt(row, 3); // Column 3: Subtotal

                    // Update the quantity and subtotal
                    int newQty = existingQty + qty;
                    double newSubtotal = newQty * buying_price;
                    model.setValueAt(newQty, row, 1); // Update Quantity
                    model.setValueAt(newSubtotal, row, 3); // Update Subtotal

                    // Exit the loop after updating the item
                    itemExists = true;
                    break;
                }
            }

            // If the product doesn't exist, add a new row to the table
            if (!itemExists) {
                model.addRow(new Object[]{
                    product.getProductName(),
                    product.getQuantity(),
                    product.getBuyingPrice(),
                    product.getSubtotal()
                });
            }

            // Clear input fields after adding
            productComboBox.setSelectedIndex(0);
            qtyTxtField.setText("");
            buyingPriceTxtField.setText("");
            sellingPriceTxtField.setText("");

            // Set focus to the productComboBox
            productComboBox.grabFocus();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

        // After adding the item, call the method to update the totals
        updateTotalLabels();
    }//GEN-LAST:event_addButtonActionPerformed

