    private void loadActiveProducts() {
        try {
            // Clear the combo box model to avoid duplicates
            productComboBoxModel.removeAllElements();

            // Add default 'Select' option
            productComboBoxModel.addElement("Select");

            // Query to fetch active products
            String query = "SELECT name FROM product WHERE status = 'Active'";
            ResultSet rs = MYSQL.executeSearch(query);

            // Populate the combo box model with product names
            while (rs.next()) {
                String productName = rs.getString("name");
                productComboBoxModel.addElement(productName);
            }

            // Set the model to the combo box
            productComboBox.setModel(productComboBoxModel);

            // Set the default selected item to 'Select'
            productComboBox.setSelectedIndex(0);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error loading product list: " + ex.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private boolean validateProductSelection() {
        if (!isProductComboBoxInteracted) {
            // User has not interacted yet; do not validate
            return true;
        }

        // Get the selected item
        String selectedProduct = (String) productComboBox.getSelectedItem();

        // Check if the selected item is null or 'Select'
        if (selectedProduct == null || selectedProduct.equals("Select")) {
            JOptionPane.showMessageDialog(this,
                    "Please select a valid product name from the list.",
                    "Invalid Selection",
                    JOptionPane.WARNING_MESSAGE);

            // Reset focus to the productComboBox
            productComboBox.requestFocus();
            return false;
        }

        // Check if the selected item is not in the combo box model
        boolean isProductValid = false;
        for (int i = 0; i < productComboBoxModel.getSize(); i++) {
            if (productComboBoxModel.getElementAt(i).equals(selectedProduct)) {
                isProductValid = true;
                break;
            }
        }

        if (!isProductValid) {
            JOptionPane.showMessageDialog(this,
                    "The entered product name is not valid. Please select a product name from the list.",
                    "Invalid Product Name",
                    JOptionPane.WARNING_MESSAGE);

            // Reset focus to the productComboBox
            productComboBox.requestFocus();
            return false;
        }

        return true; // Validation passed
    }

    private void populateOrderComboBox() {
        try {
            String orderQuery = "SELECT id FROM `order` WHERE `status` = 'Pending'";
            ResultSet orderResults = MYSQL.executeSearch(orderQuery);

            orderComboBoxModel.addElement("None"); // Add a "None" option as the first item
            while (orderResults.next()) {
                int orderId = orderResults.getInt("id");
                orderComboBoxModel.addElement(String.valueOf(orderId)); // Convert order ID to String and add
            }
            orderComboBox.setModel(orderComboBoxModel);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Failed to load order IDs: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void populateSupplierComboBox() {
        try {
            String supplierQuery = "SELECT CONCAT(first_name, ' ', last_name) AS full_name FROM `supplier` WHERE `status` = 'Active'";
            ResultSet supplierResults = MYSQL.executeSearch(supplierQuery);

            supplierComboBoxModel.addElement("Select"); // Add a "Select" option as the first item
            while (supplierResults.next()) {
                String supplierName = supplierResults.getString("full_name");
                supplierComboBoxModel.addElement(supplierName); // Add supplier name to the combo box model
            }
            supplierComboBox.setModel(supplierComboBoxModel);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Failed to load supplier names: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

