    private void checkMark() {
        try {
            ResultSet res_atEmp_HS = MYSQL.executeSearch("SELECT * FROM  `attendance`  WHERE `employee_nic`='" + attenjTextField1.getText() + "' AND `date`='" + Dateformat.format(date) + "'");
            if (res_atEmp_HS.next()) {
                if (res_atEmp_HS.getString("leaving") != null) {
                    attenjButton1.setText("You Marked");
                    attenjButton1.setBackground(Color.BLUE);
                } else {
                    attenjButton1.setText("Leaving");
                    attenjButton1.setBackground(Color.red);
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    public static void ComeAttendance(String nic, String ToDay) throws Exception {
        MYSQL.executeIUD("INSERT INTO `attendance` (`employee_nic`,`date`) VALUES ('" + nic + "','" + ToDay + "')");
    }

    public static void leaving(String nic, String leaving, String ToDay) throws Exception {
        MYSQL.executeIUD("UPDATE `attendance` SET `leaving`='" + leaving + "' WHERE `date`='" + ToDay + "' AND `employee_nic`='" + nic + "'");
    }

    private void clean() {
        attendanceLoad("WHERE `attendance`.`date`='" + Dateformat.format(date) + "'");
        attenjTextField1.setText("");
        attenjButton1.setText("Mark");
        attenjButton1.setBackground(Markcolor);
    }

