    private void attenjButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_attenjButton1ActionPerformed
        // TODO add your handling code here:
        String NIC_HS = attenjTextField1.getText();
        try {
            if (NIC_HS.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please Enter NIC.", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (!NIC_HS.matches("^[0-9]{9}[Vv]$") & !NIC_HS.matches("^[0-9]{12}$")) {
                JOptionPane.showMessageDialog(this, "Invalid NIC.", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {
                ResultSet res_atEmp_HS = MYSQL.executeSearch("SELECT * FROM `employee` LEFT JOIN `attendance` ON `employee`.`nic`=`attendance`.`employee_nic` WHERE `nic`='" + attenjTextField1.getText() + "' ORDER BY `time` DESC");

                if (res_atEmp_HS.next()) {
                    if (res_atEmp_HS.getString("nic").equals(NIC_HS) && res_atEmp_HS.getString("date") == null) {
                        ComeAttendance(NIC_HS, Dateformat.format(date));
                        clean();
                    } else if (res_atEmp_HS.getString("nic").equals(NIC_HS) && res_atEmp_HS.getString("date").equals(Dateformat.format(date)) && res_atEmp_HS.getString("leaving") != null) {
                        JOptionPane.showMessageDialog(this, "Today you have already mark form exit", "Information", JOptionPane.INFORMATION_MESSAGE);
                        //ComeAttendance(NIC_HS);
                        clean();

                    } else if (res_atEmp_HS.getString("nic").equals(NIC_HS) && res_atEmp_HS.getString("date").equals(Dateformat.format(date)) && res_atEmp_HS.getString("leaving") == null) {
                        SimpleDateFormat smptime = new SimpleDateFormat("HH:mm:ss");
                        leaving(NIC_HS, smptime.format(date), Dateformat.format(date));
                        clean();
                    } else {
                        ComeAttendance(NIC_HS, Dateformat.format(date));
                        clean();
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "This NIC does not have a Employe.", "Information", JOptionPane.INFORMATION_MESSAGE);
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_attenjButton1ActionPerformed

