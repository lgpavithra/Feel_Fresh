    private void attendanceLoad(String query) {
        try {
            AttendenceSearch(query);
            DefaultTableModel attTablemodel_HS = (DefaultTableModel) attendancejTable1.getModel();
            attTablemodel_HS.setRowCount(0);
            while (atresultSet_HS.next()) {
                Vector v = new Vector<>();
                v.add(atresultSet_HS.getString("nic"));
                v.add(atresultSet_HS.getString("fname") + " " + atresultSet_HS.getString("lname"));
                boolean isNewEmployee = false;
                if (atresultSet_HS.getString("time") == null) {
                    v.add("New Employee");
                    isNewEmployee = true;
                } else {
                    v.add(atresultSet_HS.getString("time"));
                }

                if ( (atresultSet_HS.getString("time") != null && atresultSet_HS.getString("leaving") == null) ||  isNewEmployee) {
                    v.add("Not Mark");                
                } else {
                    v.add(atresultSet_HS.getString("leaving"));
                }

                attTablemodel_HS.addRow(v);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void AttendenceSearch(String query) throws Exception {
        atresultSet_HS = MYSQL.executeSearch("SELECT * FROM `employee` LEFT JOIN `attendance` ON `employee`.`nic`=`attendance`.`employee_nic` " + query + ASC_DESC);

    }

