    HashMap<String, String> productMap_vp;

    private void loadProduct_vp() {
        /*There is a relationship between product and category_has_brand so if remove a row in category has brand
            some times it gives a SQLIntegrityConstraintViolationException when that has foriegned with product table.
            Here we load product to a hashmap to identify if there are a relationshp like above*/
        productMap_vp = new HashMap<>();

        try {

            ResultSet rsProduct_vp = MYSQL.executeSearch("SELECT * FROM `product` ");
            while (rsProduct_vp.next()) {
                productMap_vp.put(rsProduct_vp.getString("brand_id"), rsProduct_vp.getString("category_id"));
            }

        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

    HashMap<String, Integer> brandMap;

    private void loadBrand_vp(String where) {
        brandMap = new HashMap<>();
        String query = "SELECT * FROM `brand`   " + where;

        DefaultListModel<String> listModel = new DefaultListModel<>();

        listModel.setSize(0);

        try {
            //Load brand
            ResultSet rsBrand_vp = MYSQL.executeSearch(query);

            while (rsBrand_vp.next()) {

                listModel.addElement(rsBrand_vp.getString("name"));

                brandMap.put(rsBrand_vp.getString("name"), rsBrand_vp.getInt("id"));
            }

            jList1.setModel(listModel);

        } catch (Exception ex) {
            ex.printStackTrace();
        }

    }

