    private void jToggleButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1ActionPerformed
//        System.out.println(jList1.getSelectedIndex());
        if (jList1.getSelectedIndex() == -1 || jList2.getSelectedIndex() == -1) {//not selected anything
            JOptionPane.showMessageDialog(this, "Please Select a Brand and a Category", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            if (jToggleButton1.isSelected()) {

                try {
                    MYSQL.executeIUD("INSERT INTO `category_has_brand` (`category_id` , `brand_id`) "
                            + " VALUES ('" + categoryMap.get(jList2.getSelectedValue()) + "'  , '" + brandMap.get(jList1.getSelectedValue()) + "'  )  ");
                } catch (Exception ex) {
                    ex.printStackTrace();
                }

            } else {
                try {
                    boolean canDelete = true;
                    for (Map.Entry<String, String> entry : productMap_vp.entrySet()) {
                        String key = entry.getKey();
                        String val = entry.getValue();

                        if (key.equals(String.valueOf(brandMap.get(jList1.getSelectedValue())))) {//is there a r-ship with brand

                            if (val.equals(String.valueOf(categoryMap.get(jList2.getSelectedValue())))) {// is there a r-ship with category
                                System.out.println("1111key : " + key + " val : " + val);

                                canDelete = false;
                                break;
                            }
                            //if there is it foreigned

                            System.out.println("222key : " + key + " val : " + val);

                        }
                    }

                    if (canDelete) {
                        MYSQL.executeIUD("DELETE FROM `category_has_brand` "
                                + "WHERE `category_id` = '" + categoryMap.get(jList2.getSelectedValue()) + "' "
                                + " AND `brand_id` = '" + brandMap.get(jList1.getSelectedValue()) + "'  ");
                    } else {
                        JOptionPane.showMessageDialog(this, "Sorry this is foreigned with a product", "Can't delete", JOptionPane.WARNING_MESSAGE);
                    }

                } catch (Exception ex) {
                    ex.printStackTrace();
                }
            }

        }

        reset_vp();


    }//GEN-LAST:event_jToggleButton1ActionPerformed

