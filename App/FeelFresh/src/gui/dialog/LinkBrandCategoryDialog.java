    private void loadTable_vp(String where) {
        //This method loads brand and categories 

        DefaultTableModel tm_vp = (DefaultTableModel) jTable2.getModel();
        tm_vp.setRowCount(0);

        String query_vp = "SELECT * FROM `brand` "
                + "INNER JOIN `category_has_brand` ON `brand`.`id` = `brand_id` "
                + "INNER JOIN `category` ON `category`.`id` = `category_id` " + where;
        try {
            ResultSet rsLinked_vp = MYSQL.executeSearch(query_vp);

            while (rsLinked_vp.next()) {
                Vector<String> tableVector_vp = new Vector<>();
                tableVector_vp.add(rsLinked_vp.getString("brand.name"));
                tableVector_vp.add(rsLinked_vp.getString("category.name"));

                tm_vp.addRow(tableVector_vp);

            }

        } catch (Exception ex) {
            ex.printStackTrace();
        }

    }

