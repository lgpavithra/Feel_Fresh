    private void loadSuppleir_vp(String q) {

        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);

        q = " SELECT * FROM `supplier` INNER JOIN `supplier_mobile` ON `supplier`.`id` = `supplier_mobile`.`supplier_id` "
                + " WHERE `status` = 'Active' " + q;


        try {

            //select all the active suppliers 
            ResultSet resultSet = MYSQL.executeSearch(q);

            while (resultSet.next()) {
                Vector<String> vector = new Vector();
                vector.add(resultSet.getString("id"));
                vector.add(resultSet.getString("first_name") + "  " + resultSet.getString("last_name"));
                vector.add(resultSet.getString("email"));
                vector.add(resultSet.getString("mobile"));

                dtm.addRow(vector);

            }

            jTable1.setModel(dtm);
            SwingUtilities.updateComponentTreeUI(jTable1);

        } catch (Exception ex) {
            ex.printStackTrace();
        }

    }

