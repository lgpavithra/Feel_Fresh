    private void search_vp() {
        String q = "";
        String email = jTextFieldEmail.getText();
        String name = jTextFieldName.getText();
        if (email.length() >= 6 && email.substring(0, 6).equals("Search")) {

        } else {
            q += "AND (`email` LIKE '" + email + "%' "                   
                    + "OR `mobile` LIKE '" + email + "%'  ) ";
        }

        if (name.length() >= 6 && name.substring(0, 6).equals("Search")) {
        } else {

            q += " AND (CONCAT(`first_name`, `last_name`) LIKE '" + name.trim().replace(" ", "") + "%' "
//                    + " OR `first_name`  LIKE '" + name + "%' "
                    + " OR `last_name`  LIKE '" + name + "%'   )";
        }

        loadSuppleir_vp(q);

    }

